-- 계정 삭제 (기술 설계서 §11.3).
--
-- 행을 지우지 않고 **개인을 식별하는 값을 지운다.** 제출과 판정 이력이 user_id 를
-- 참조하고(§8.1), 문제별 통계도 그 위에 선다. 행을 지우면 "이 문제가 몇 번 풀렸는가"가
-- 함께 사라지는데, 그것은 지워 달라고 요청받은 것이 아니다.
--
-- 지우는 것은 이메일·표시 이름·비밀번호 해시다. 남는 것은 식별할 수 없는 id 와,
-- 그 id 에 달린 판정 사실뿐이다.

ALTER TABLE app_user
    ADD COLUMN deleted_at TIMESTAMPTZ;

COMMENT ON COLUMN app_user.deleted_at IS
    '삭제 요청을 처리한 시각. 이후 로그인은 거절된다 (§11.3).';

-- 이메일은 유니크다. 지운 계정의 이메일 자리를 비워 두면 같은 주소로 다시 가입할 수
-- 없다. 무덤값으로 바꿔 자리를 내주되, 그 값이 실제 주소와 겹치지 않게 한다.
