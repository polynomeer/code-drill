-- 지운 계정의 소스를 비울 수 있게 한다 (기술 설계서 §11.3).
--
-- 제출 행은 남긴다. 판정 이력이 이 행을 참조하고(§8.1) 문제별 통계가 그 위에 서므로,
-- 행을 지우면 "이 문제가 몇 번 풀렸는가"까지 함께 사라진다 — 그건 지워 달라고 요청받은
-- 것이 아니다.
--
-- 지워야 할 것은 **그 사람이 쓴 코드**다. NOT NULL 이면 비울 수가 없어, 자리를 채우려고
-- 가짜 문자열을 넣게 된다. "소스가 없다"는 실제로 있는 상태이므로 NULL 로 표현한다.
--
-- 소스가 없는 제출은 재채점할 수 없다. 그것도 맞는 결과다 — 지운 코드를 다시 돌릴 수는
-- 없고, 돌릴 수 있다면 지운 것이 아니다.

ALTER TABLE submission ALTER COLUMN source DROP NOT NULL;

COMMENT ON COLUMN submission.source IS
    '제출 소스. 계정을 지우면 NULL 이 된다 (§11.3).';
