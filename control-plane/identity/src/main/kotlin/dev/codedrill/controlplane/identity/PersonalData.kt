package dev.codedrill.controlplane.identity

/**
 * 계정 하나에 딸린 개인 데이터 (기술 설계서 §11.3).
 *
 * Identity 는 다른 도메인 모듈을 참조하지 않는다 (§3.1). 그런데 사용자가 "내 데이터를
 * 내려 달라" 또는 "지워 달라"고 하면 답해야 하는 것은 계정만이 아니다 — 제출한 소스,
 * 저장해 둔 초안, 실행 트레이스가 전부 그 사람의 것이다.
 *
 * 그래서 각 모듈이 자기 몫을 이 계약으로 내놓고, 어댑터는 `:control-plane:app` 이 잇는다.
 *
 * **새 모듈이 개인 데이터를 갖게 되면 여기에 붙여야 한다.** 붙이지 않으면 반출은 조용히
 * 빠뜨리고 삭제는 조용히 남긴다. 둘 다 법적 의무를 지키지 못한 것이며, 그 사실이
 * 드러나는 것은 대개 요청을 받은 뒤다.
 */
interface PersonalData {

    /** 로그·응답에 쓰는 이름. 반출 결과의 키가 된다. */
    val area: String

    /** 이 사람에 대해 갖고 있는 것 전부. 반출 파일에 그대로 실린다. */
    fun export(userId: String): Any

    /**
     * 지운다. 무엇을 몇 건 지웠는지 돌려준다.
     *
     * **전부 지우는 것이 답이 아닌 경우가 있다.** 판정 결과는 문제의 통계와 다른
     * 사람의 순위에 얽혀 있고, 감사 로그는 append-only 다 (§13.3). 개인을 식별하는
     * 것과 그 사람이 쓴 내용을 지우되, 집계에만 쓰이는 사실은 남긴다.
     */
    fun erase(userId: String): Map<String, Int>
}
