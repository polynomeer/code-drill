package dev.codedrill.controlplane.competency

import dev.codedrill.platform.problempackage.Competency
import java.time.Instant
import java.util.UUID

/**
 * 역량 증거 하나 (기획서 §4.2).
 *
 * **사건이지 점수가 아니다.** 사용자가 무엇을 했고 그것이 성공이었는지를 적을 뿐, 숙련도는
 * 여기에 없다 — 숙련도는 증거의 함수이며 [Mastery] 가 그때그때 계산한다.
 *
 * 그렇게 나눠 두면 계산 규칙을 고쳐도 지난 증거를 다시 해석할 필요가 없다. 규칙을 고치고
 * 다시 계산하면 끝이다.
 */
data class Evidence(
    val id: UUID,
    val userId: String,
    val competency: Competency,
    val source: EvidenceSource,
    val success: Boolean,
    /**
     * 이 증거의 무게 (§3.4).
     *
     * 지금은 전부 1.0 이다. 도움 기능(힌트·AI)이 붙으면 그것을 쓴 증거의 무게가 낮아진다 —
     * 도움을 받아 맞힌 것과 혼자 맞힌 것은 같은 증거가 아니다.
     */
    val weight: Double,
    val problemId: String,
    /** 원본을 가리키는 값. 화면이 이것으로 제출이나 응답을 연다 (FR-806). */
    val reference: String?,
    /** 사람이 읽을 한 줄. */
    val detail: String?,
    val occurredAt: Instant,
)

/**
 * 증거의 출처 (기획서 §8.2 관찰 신호).
 *
 * 원본이 세는 신호는 이보다 많다 — 힌트 의존도, 변이 탐지율, 반례 품질, 설명-코드 일치.
 * **없는 신호를 목록에 적어 두지 않는다.** 적어 두면 화면이 "아직 측정되지 않음"과 "그런
 * 신호가 없음"을 같게 보여주고, 그 둘은 다르다.
 */
enum class EvidenceSource {
    /** 판정된 제출. 문제의 역량 태그가 가리키는 역량 전부에 증거가 된다. */
    SUBMISSION,

    /** 풀이 전 질문 응답 (FR-803). 예측이 맞았는지를 본다. */
    PREQUESTION,

    /** 사용자가 직접 만든 테스트 (부록 A 실행 도메인). 무엇을 시험해야 하는지 아는가. */
    TRIAL,

    /**
     * 그 테스트를 대표 오답에 겨눈 결과 (FR-804).
     *
     * [TRIAL] 과 나눈다. 저것은 "기대 출력을 적었다"까지만 말하고, 이것은 그 기대가
     * 실제로 결함을 잡았는지를 말한다 — 같은 표시로 두면 화면이 그 둘을 가릴 수 없다.
     */
    MUTATION,

    /**
     * 코칭 후 힌트 없이 변형 문제를 통과했다 (FR-807).
     *
     * [SUBMISSION] 과 나눈다. 같은 판정에서 나오지만 말하는 것이 다르다 — 저것은
     * "이 문제를 풀었다"이고 이것은 "배운 것이 다른 문제로 옮겨졌다"이며, 후자가
     * 코칭이 효과가 있었는지를 재는 유일한 증거다.
     */
    TRANSFER,

    /**
     * 리플레이에서 다음 이벤트를 맞혀 봤다 (FR-805).
     *
     * 무게가 낮다. 트레이스는 이미 화면에 있어 마음먹으면 답을 보고 누를 수 있고,
     * 감출 수 없는 구멍이면 감추는 척하는 대신 값을 낮춰 세는 것이 맞다.
     */
    PREDICTION,

    /** 아레나에서 오답을 깨뜨려 봤다 (§8.3). 반례를 만드는 역량의 가장 직접적인 증거다. */
    ARENA,

    /**
     * 프로젝트형 판정 (11단계). 숨은 스위트를 전부 통과했는가 — 요구사항 충실의 증거다.
     *
     * [SUBMISSION] 과 나눈다. 둘 다 판정이지만 다른 판정기에서 나오고 다른 칸(실무군)에
     * 붙는다. 같은 출처로 두면 화면이 "알고리즘 문제를 풀었다"와 "요구사항을 코드로
     * 옮겼다"를 가릴 수 없다.
     */
    PROJECT,

    /**
     * 프로젝트 제출에서 사용자가 시작 저장소보다 테스트를 더 썼다 (11단계).
     *
     * [PROJECT] 와 나눈다. 같은 제출에서 나오지만 말하는 것이 다르다 — 저것은 "요구사항을
     * 맞혔다"이고 이것은 "자기 구현을 시험하는 코드를 썼다"다. 더한 테스트가 자기 제출에서
     * 통과했는가가 성공이다. 시작 저장소 그대로면 증거가 없다 — 안 쓴 것은 못 쓰는 것의
     * 증거가 아니다.
     */
    PROJECT_TESTS,
}
